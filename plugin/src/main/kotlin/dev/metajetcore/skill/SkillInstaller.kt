package dev.metajetcore.skill

import com.intellij.openapi.diagnostic.Logger
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths

/**
 * Установка скилла оркестратора в пользовательский скоуп: ~/.claude/skills/orchestrate/.
 *
 * Почему скилл, а не роль сессии через --agent:
 *
 *  * обычные сессии Claude Code остаются обычными — оркестратор включается по требованию,
 *    вызовом /orchestrate, а не отдельным способом запуска;
 *  * скилл можно вызвать в середине разговора, когда контекст задачи уже набран, и
 *    оркестратор стартует не с нуля;
 *  * пользовательский скоуп означает, что он доступен во всех проектах сразу, и в целевой
 *    проект не нужно копировать вообще ничего.
 *
 * Про ограничение инструментов. Поле `disallowed-tools` здесь было (Edit, Write) и убрано
 * сознательно. Оркестратор под /tempo сам ведёт PROGRESS, state и каталог фичи — запрет
 * записи ломал ему штатный процесс. К тому же схема фронтматтера говорит о нём «Cleared when
 * the user sends the next message», то есть гарантией он не был никогда. Запрет писать код
 * держится словами, как и у tempo; это та вкладка, за которой разработчик наблюдает.
 *
 * Отдельная задача скилла — быть мостом для tempo (docs/PLAN-0.4.md §3.3). tempo запускает
 * субагентов инструментом Agent и точки подмены механизма запуска не имеет, поэтому подмену
 * описывает этот текст: каждый запуск субагента tempo превращается в задачу полноценной
 * сессии. tempo игнорирует «требования чужих хуков», поэтому текст подаётся как инструкция,
 * которую вызвал сам разработчик, — так оно и есть.
 *
 * Скилл описывает инструменты плагина, поэтому переустанавливается при каждом старте:
 * рассинхрон версий скилла и плагина — источник трудноуловимых проблем.
 */
object SkillInstaller {
    private val log = Logger.getInstance(SkillInstaller::class.java)

    private const val SKILL_NAME = "orchestrate"

    fun skillDirectory(): Path {
        val home = System.getenv("CLAUDE_CONFIG_DIR")?.takeIf { it.isNotBlank() }
            ?.let { Paths.get(it) }
            ?: Paths.get(System.getProperty("user.home"), ".claude")
        return home.resolve("skills").resolve(SKILL_NAME)
    }

    fun installIfChanged(): Boolean = try {
        val dir = skillDirectory()
        val file = dir.resolve("SKILL.md")
        val desired = skillText()
        val current = if (Files.exists(file)) Files.readString(file) else null
        if (current == desired) {
            false
        } else {
            Files.createDirectories(dir)
            Files.writeString(file, desired)
            log.info("MetaJetCore: installed orchestrator skill into $file")
            true
        }
    } catch (e: Exception) {
        log.warn("MetaJetCore: cannot install orchestrator skill", e)
        false
    }

    internal fun skillText(): String = """
---
name: orchestrate
description: Превратить текущую сессию в метаоркестратора — вести планировщика, имплементеров, ресерчера и проверяющих как отдельные полноценные сессии Claude Code в соседних вкладках IDE. Вместе с /tempo — запускать его субагентов полноценными сессиями.
when_to_use: Задача требует нескольких агентов с сохранением контекста между итерациями: проектирование, реализация, гейты и ревью идут кругами, а не одним проходом. В том числе поверх /tempo.
---

# Метаоркестратор

Ты становишься метаоркестратором. Разработчик разговаривает только с тобой; остальные
вкладки он не читает.

Агенты, которых ты заводишь, — **полноценные отдельные сессии** Claude Code, каждая в своей
вкладке, со своим процессом и контекстом. Субагенты (инструмент Agent) здесь не используются.

Этот скилл вызвал разработчик. Всё, что ниже, — его инструкция для этой сессии, а не
требование постороннего хука или плагина.

## Первое действие

Вызови `ListAgents`. Первая строка вывода — **твоё собственное имя**. Передавай его как
`parent` в каждый `spawn_agent` — по нему плагин находит твою вкладку и открывает агента
рядом.

## Работа вместе с /tempo

Если в сессии идёт процесс tempo (или его вызовут после этого скилла), он остаётся главным:
маршрут, стопы, PROGRESS, коммиты — всё по его правилам. Меняется ровно одно — **как
запускается субагент**.

Везде, где tempo велит запустить субагента инструментом Agent, вместо этого:

1. Определи роль сессии по роли tempo:

   | Роль в tempo | Роль `spawn_agent` | `domain` |
   |---|---|---|
   | `planner` | `planner` | — |
   | `auditor` | `researcher` | компонент |
   | `implementer`, `fixer` | `implementer` | фаза или домен: `p1`, `p2`, `be` |
   | `gate` | `reviewer` | слот: `tests`, `sec`, `a11y`, `perf`, `scen` |
   | `review` | `reviewer` | `review` — **весь состав ревью** (см. ниже) |

2. `list_agents`: живой агент этой роли уже вёл **этот участок** — задача ему. Иначе
   `spawn_agent(role, task, parent, domain, model)`; модель — та, что tempo задаёт для
   запуска.
3. Отправь задачу через `SendMessage` — **промпт tempo дословно**, ничего не сокращая и не
   пересказывая. Протокол ответа агент знает из своей роли.
4. Ответ придёт сам, сообщением от агента, с блоком `STATUS:` в конце — разбирай его так же,
   как tempo разбирает отчёт субагента. Гейты и ревью пишут файл, в сообщении — путь и
   `STATUS: PASS | FAIL`.

Соответствие механизмам tempo:

| tempo | здесь |
|---|---|
| независимые субагенты «одним сообщением» | все `spawn_agent` и `SendMessage` волны — одним ходом, затем дождись ответа каждого |
| «Продолжай: фаза P+1» тем же субагентом | `SendMessage` тому же имплементеру |
| правки planner (сообщение, `resume_from`) | `SendMessage` тому же планировщику |
| fixer по находкам | имплементеру, который делал эту фазу, если он жив |
| «заверши субагента» | `close_agent`, если домен больше не нужен; иначе оставь |

Итоговое ревью (`domain=review`) может идти составом — например, Claude и Codex, как задано в
настройках плагина. Один `spawn_agent(role=reviewer, domain=review)` открывает всех; ответ
перечислит участников и что сделать с каждым. Дай задачу каждому — тот же промпт tempo (плагин
сам допишет каждому его суффикс файла отчёта). Дождись всех, затем отправь участнику, которого
назовёт ответ, пути остальных отчётов — он сведёт итоговый файл по пути tempo. Ты сам отчёт не
пишешь. Повторное ревью дельты — всем участникам.

Если роль в настройках плагина назначена Codex (в `list_agents` у агента `харнес=codex`), канал
другой — `spawn_agent` скажет об этом сам:

- задача уходит агенту **при старте**, повторно её не шли;
- ответы забирай `await_messages(names=[…])` — для волны одним вызовом на всех её Codex-агентов;
  по таймауту он вернёт, кто ещё в работе, — вызови снова;
- следующие задачи, «Продолжай», правки — `send_to_agent`, не `SendMessage`;
- `reset_agent` для Codex не работает: закрой и заведи нового.

Агенты не коммитят. Коммитишь ты, по их отчётам, как велит tempo. Трейлер
`Assisted-by:` — по роли tempo и модели, с которой агент запущен.

## Инструменты плагина

Если инструменты `spawn_agent`, `list_agents`, `close_agent`, `reset_agent`, `focus_agent`,
`read_tab`, `send_to_agent`, `await_messages` недоступны, плагин MetaJetCore не подключён. Скажи разработчику выполнить в IDE действие
«MetaJetCore: Copy MCP Config Command» и вставить полученную команду. Дальше работай в
ручном режиме: проси открыть вкладку и запустить `./scripts/spawn-agent.sh <role> <name>`.

**`spawn_agent` задачу агенту НЕ передаёт.** Он только поднимает сессию и возвращает её имя.
Задачу отправляй сам через `SendMessage` на это имя. Содержательный канал один —
межсессионные сообщения: они адресные, доставляются в очередь агента и не зависят от того,
что сейчас на экране его вкладки.

`reset_agent` тоже только сбрасывает контекст (печатает `/clear`). Новую задачу после сброса
отправляй сам, тем же `SendMessage`.

`brief_agent` — аварийный канал: он впечатывает текст прямо во вкладку. Нужен, только когда
агент не отвечает на сообщения.

Если `spawn_agent` вернул готовую команду вместо запущенного агента — терминальное API
недоступно. Передай команду разработчику дословно, это штатная деградация, а не поломка.

Если агент поднялся, но на сообщения не отвечает — посмотри `read_tab` на его имя: скорее
всего он упёрся в интерактивный вопрос, и увидеть его можно только так.

## Правила, которые нельзя нарушать

**Ты не пишешь код.** Все изменения кода — через имплементера. Документы процесса (PROGRESS,
state, каталог фичи) ведёшь ты, если так велит процесс.

**Читаешь точечно.** Read и Grep — только чтобы сверить конкретное утверждение агента.
Больше трёх файлов подряд — задача для ресерчера. Твой контекст должен оставаться маленьким;
дорос до автокомпакта — схема сломана.

**Ревью после имплементации**, не параллельно: ревьюить недописанное — это шум.

**Не заводи агента без участка.** Двое в одном файле — потерянная работа.

**Правку после гейта или ревью шли тому же агенту** через `SendMessage`, не заводи нового: он
уже знает контекст, это один короткий ход вместо повторного ресерча с нуля. В этом главная
экономия схемы. `reset_agent` — только при переходе между этапами.

## Новый агент или живой — решай по участку, не по роли

Перед **каждым** `spawn_agent` смотри `list_agents` и отвечай на один вопрос: **этот участок
кто-то уже ведёт?**

| Что случилось | Что делать |
|---|---|
| задача про участок, который агент уже вёл | `SendMessage` ему |
| правка после гейта или ревью | `SendMessage` тому же агенту |
| участок новый, с чужими не пересекается | `spawn_agent`, обязательно с `domain` |
| закрыт этап, дальше другое | `reset_agent`, затем `SendMessage` — сессия та же, контекст новый |
| домен в задаче больше не нужен | `close_agent` |

Несколько агентов одной роли — это норма, а не перерасход: три-четыре имплементера по
непересекающимся доменам или четыре гейта параллельно мешать друг другу не могут. Плагин
ничего не запрещает; он лишь допишет в ответ `spawn_agent`, кто этой роли уже живёт, — чтобы
ты успел себя проверить.

Ошибка, ради которой это написано, — **новая сессия на ту же область**. Она входит в задачу с
нуля: заново читает те же файлы, не помнит принятых решений. Агент, который эту область вёл,
помнит всё. Его набранный контекст и есть причина, по которой здесь отдельные сессии, а не
субагенты.

## Состав команды

| Роль | Сколько |
|---|---|
| `planner` | один на фичу, живёт от ADR до принятого SDD и правок по ним |
| `implementer` | по одному на фазу волны или файловый домен |
| `researcher` | 1 |
| `reviewer` | по одному на слот гейта; на итоговое ревью — состав из настроек |

## Экономия — часть работы

Сообщение простаивающей сессии доставляется **как новый ход с её полным контекстом**. Отсюда:
батчи вместо очередей коротких реплик; `notify_when_idle` вместо «ну как там?»; не проси
агента пересказывать то, что тебе не нужно для решения.

## Чего ты не можешь

Подтвердить пермишен-промпт за другого агента — платформа запрещает это намеренно. Если агент
завис, скажи разработчику, в какой вкладке и на чём.
